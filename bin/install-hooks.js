#!/usr/bin/env node

// This is a simplified version of the install-hooks script
// that doesn't require ts-node to run during package installation

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Get the current working directory (user's project)
const cwd = process.cwd();

async function installGitHooks() {
  try {
    console.log('Installing Git hooks...');

    // Check if .git directory exists
    const gitDir = path.join(cwd, '.git');
    const gitHooksDir = path.join(gitDir, 'hooks');

    if (!fs.existsSync(gitDir)) {
      console.error(
        'Not a git repository. Please run this command in a git repository.',
      );
      return;
    }

    // Create hooks directory if it doesn't exist
    if (!fs.existsSync(gitHooksDir)) {
      console.log(`Creating git hooks directory: ${gitHooksDir}`);
      fs.mkdirSync(gitHooksDir, { recursive: true });
    }

    // Create pre-commit hook
    const preCommitPath = path.join(gitHooksDir, 'pre-commit');
    const preCommitContent = `#!/bin/sh
# Generated by changelog-generator

# Run the changelog generator
npx changelog-generator

# Add the generated changelog to the commit
git add docs/changelogs/

# Exit with success
exit 0
`;

    // Write the hook file
    fs.writeFileSync(preCommitPath, preCommitContent, 'utf8');

    // Make it executable (on Unix systems)
    try {
      fs.chmodSync(preCommitPath, '755');
    } catch (error) {
      console.warn(
        'Could not set executable permissions. You may need to do this manually.',
      );
    }

    console.log(`Git pre-commit hook installed at: ${preCommitPath}`);
    console.log('Git hooks installed successfully');
  } catch (error) {
    console.error(`Error installing Git hooks: ${error.message}`);
    process.exit(1);
  }
}

// Execute the function
installGitHooks();
